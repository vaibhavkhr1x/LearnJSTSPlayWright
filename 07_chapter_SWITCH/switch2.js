let day = 2;
//day 1 - monday, day 2 - tuesday ........
switch(day){
    case 0:
        console.log("Sunday");
        
    case 1:
        console.log("Monday");
        
    case 2:
        console.log("Tuesday");
        
    case 3:
        console.log("Wednesday");
        
    case 4:
        console.log("Thursday");
        
    case 5:
        console.log("Friday");
        
    case 6:
        console.log("Saturday");
    
    default:
        console.log("Invalid day");
}
